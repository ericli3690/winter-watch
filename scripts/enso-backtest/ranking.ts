import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { join } from 'node:path'
import { classifyFlavor, type EnsoState } from '../../src/lib/enso'
import { classifyPhase, classifyStrength, eventMagnitude } from '../../src/lib/enso-scale'
import { RESORTS } from '../../src/lib/resorts'
import { seasonalScore } from '../../src/lib/score'
import { getWeeklySst, OUT_DIR } from './data'
import { fmt, fmtU } from './stats'


/** One resort's seasonal standing at one ocean state. */
interface Row {
  id: string
  name: string
  region: string
  score: number
  effect: number
}

/** A board, as the script saved it for one version of the scoring code. */
interface Board {
  label: string
  week: string
  nino12: number
  nino34: number
  nino4: number
  rows: Row[]
}

/**
 * The latest CPC week, built into the state the app ranks on.
 *
 * @remarks
 * - Read live from the same weekly file as `getEnsoState`, never typed in.
 * - The ONI fields are left empty because the seasonal score does not read them.
 */
async function currentState(): Promise<EnsoState> {
  const rows = await getWeeklySst()
  const latest = rows[rows.length - 1]
  const { flavor, epGradient } = classifyFlavor(latest)
  return {
    ...latest,
    weekEnding: latest.week,
    phase: classifyPhase(latest.nino34),
    strength: classifyStrength(latest.nino34),
    flavor,
    epGradient,
    magnitude: eventMagnitude(latest.nino34),
    oniSeason: null,
    oniValue: null,
    nino34History: [],
    fetchedAt: new Date().toISOString(),
  }
}

/** Ranking order with an id tie-break, so equal scores keep a stable order. */
const byScore = (a: Row, b: Row) => b.score - a.score || a.id.localeCompare(b.id)

/** How much a board separates resorts: the properties a saturated board loses. */
function discrimination(rows: Row[]) {
  const top = [...rows].sort(byScore)
  const pinned = rows.filter((r) => Math.abs(r.effect) >= 0.999).length
  const distinctTop20 = new Set(top.slice(0, 20).map((r) => r.score.toFixed(1))).size
  return { pinned, distinctTop20, top20Spread: top[0].score - top[19].score }
}

/** The before/after comparison, written as Markdown. */
function compare(before: Board, after: Board): string {
  const b = [...before.rows].sort(byScore)
  const a = [...after.rows].sort(byScore)
  const rankB = new Map(b.map((r, i) => [r.id, i + 1]))
  const rowB = new Map(b.map((r) => [r.id, r]))
  const db = discrimination(before.rows)
  const da = discrimination(after.rows)
  const lines = [
    '# Seasonal ranking at 2026–27 inputs, before and after',
    '',
    `Generated by \`pnpm backtest:ranking\` from the live CPC weekly file, week of ${after.week}:`,
    `Niño 1+2 ${fmt(after.nino12, 1)} °C, Niño 3.4 ${fmt(after.nino34, 1)} °C, Niño 4 ${fmt(after.nino4, 1)} °C.`,
    'Seasonal score only. The northern preseason GFS is empty, so live mode does not apply.',
    'This is the app’s model ranking, not a snowfall forecast.',
    '',
    '| | Before | After |',
    '| --- | ---: | ---: |',
    `| Resorts with the teleconnection effect pinned at ±1 | ${db.pinned} | ${da.pinned} |`,
    `| Distinct scores (0.1 pt) among the top 20 | ${db.distinctTop20} | ${da.distinctTop20} |`,
    `| Score spread, #1 to #20 | ${fmtU(db.top20Spread, 1)} | ${fmtU(da.top20Spread, 1)} |`,
    '',
    '| After | Resort | Region | Effect | Score | Before | Effect | Score | Move |',
    '| ---: | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |',
  ]
  a.forEach((r, i) => {
    const old = rowB.get(r.id)!
    const move = rankB.get(r.id)! - (i + 1)
    lines.push(
      `| ${i + 1} | ${r.name} | ${r.region} | ${fmt(r.effect)} | ${fmtU(r.score, 1)} | ${rankB.get(r.id)} | ${fmt(old.effect)} | ${fmtU(old.score, 1)} | ${move === 0 ? '·' : fmt(move, 0)} |`,
    )
  })
  return lines.join('\n') + '\n'
}

/** Save this side's board, and write the comparison once both sides exist. */
async function main() {
  const label = process.argv[2]
  if (label !== 'before' && label !== 'after') throw new Error('usage: ranking.ts before|after')
  const enso = await currentState()
  const rows = RESORTS.map((r) => {
    const { score, effect } = seasonalScore(r, enso)
    return { id: r.id, name: r.name, region: r.region, score, effect }
  })
  const board: Board = {
    label,
    week: enso.weekEnding,
    nino12: enso.nino12,
    nino34: enso.nino34,
    nino4: enso.nino4,
    rows,
  }
  await mkdir(OUT_DIR, { recursive: true })
  await writeFile(join(OUT_DIR, `ranking-${label}.json`), JSON.stringify(board, null, 2) + '\n')
  console.log(`${label}: week ${board.week}, Nino 3.4 ${board.nino34}`, discrimination(rows))

  const other = label === 'before' ? 'after' : 'before'
  try {
    const otherBoard = JSON.parse(await readFile(join(OUT_DIR, `ranking-${other}.json`), 'utf8')) as Board
    const [before, after] = label === 'before' ? [board, otherBoard] : [otherBoard, board]
    await writeFile(join(OUT_DIR, 'ranking.md'), compare(before, after))
    console.log('wrote ranking.md')
  } catch {
    // Only one side saved so far.
  }
}

main()
