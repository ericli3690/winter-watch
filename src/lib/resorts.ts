import type { Access, PassId, Resort } from './types'

const unlimited = (note?: string): Access => ({ kind: 'unlimited', blackouts: false, note })
/** Unlimited access that still honours the holiday blackout calendar. */
const unlimitedBlackout = (note?: string): Access => ({ kind: 'unlimited', blackouts: true, note })
const days = (n: number, blackouts = true, note?: string): Access => ({
  kind: 'days',
  days: n,
  blackouts,
  note,
})

/** Ikon tiers; pass `null` where the Base tier does not reach the mountain. */
const ikon = (
  full: Access,
  base: Access | null,
): Partial<Record<PassId, Access>> => (base ? { ikon: full, 'ikon-base': base } : { ikon: full })

/** Full-Ikon only -- the Base tier does not reach this mountain at all. */
const ikonOnly = (full: Access): Partial<Record<PassId, Access>> => ({ ikon: full })

/** Epic tiers; pass `null` where Epic Local does not reach the mountain. */
const epic = (
  full: Access,
  local: Access | null,
): Partial<Record<PassId, Access>> =>
  local ? { epic: full, 'epic-local': local } : { epic: full }

/** A dated range the holiday calendar blacks out. */
export interface BlackoutDate {
  range: string
  label: string
}

